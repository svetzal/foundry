//! The scratch directory of one agent run, outside the project checkout.
//!
//! Every coding-agent session gets one, at
//! `{evidence_dir}/{trace_id}/{attempt}/`, and sees it as
//! [`foundry_sdk::paths::SCRATCH_DIR_ENV`]. The executor writes its proof
//! ([`PROOF_FILE`]), its blocker ([`BLOCKER_FILE`]) and its command logs
//! ([`LOGS_DIR`]) there; review and finalize read them from there. Because the
//! directory is in the evidence store, it is the durable record of the run
//! too: the daemon's evidence retention prunes it with its trace.
//!
//! Nothing here is in the project's repository, so no commit can pick it up.
//! A directory in the evidence store also keeps the project checkout clean:
//! in October and November 2026, agents told to log into `.foundry/logs`
//! inside the checkout had thousands of those logs committed by the
//! maintenance commit.
//!
//! Agents can also leave build output in their scratch (a coverage
//! `CARGO_TARGET_DIR`, an integration checkout with its `deps` and
//! `_build`). That is gigabytes of regenerable output, and keeping it filled
//! the ops host's disk once. So Finalize Task trims the directory
//! ([`trim`]): it removes every regenerable directory ([`REGENERABLE_DIRS`])
//! and every file larger than [`KEPT_FILE_CAP_BYTES`], and records what it
//! removed in [`TRIMMED_RECORD_FILE`].

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::Serialize;

/// The early-proof record, relative to the scratch directory.
pub(crate) const PROOF_FILE: &str = "proof.json";

/// The record a campaign executor writes in place of [`PROOF_FILE`] when it
/// cannot reach the acceptance boundary because a capability, access or owner
/// decision is missing. Review turns a valid one into a question for the
/// owner rather than a missing-proof defect.
pub(crate) const BLOCKER_FILE: &str = "blocker.json";

/// Where `foundry capture` writes its logs inside the scratch directory.
pub(crate) const LOGS_DIR: &str = "logs";

/// The payload key that carries the scratch directory through a run's chain
/// (see [`foundry_sdk::payload::LoopContext::scratch_dir`]).
const PAYLOAD_KEY: &str = "scratch_dir";

/// Create a new, empty scratch directory for one run attempt of `trace_id`
/// under `evidence_root`, with its [`LOGS_DIR`].
pub(crate) fn allocate(evidence_root: &Path, trace_id: &str) -> std::io::Result<PathBuf> {
    let directory = evidence_root.join(trace_id).join(uuid::Uuid::new_v4().to_string());
    std::fs::create_dir_all(directory.join(LOGS_DIR))?;
    Ok(directory)
}

/// The trace directory a session's scratch goes under: its trace, or for an
/// untraced session a trace directory of its own, so the evidence retention
/// can still age it out.
fn trace_dir_name(trace_id: Option<&str>) -> String {
    trace_id.map_or_else(|| uuid::Uuid::new_v4().to_string(), str::to_string)
}

/// A new scratch directory in Foundry's evidence store for a session of
/// `trace_id`.
pub(crate) fn allocate_in_evidence_store(trace_id: Option<&str>) -> std::io::Result<PathBuf> {
    allocate(&foundry_sdk::paths::evidence_dir(), &trace_dir_name(trace_id))
}

/// Give the run in `payload` a new scratch directory and record it there,
/// replacing any it inherited. A task run starts with this, so a resumed or
/// continued task never reads the proof of the run it continues.
pub(crate) fn allocate_into(
    payload: &mut serde_json::Value,
    evidence_root: &Path,
    trace_id: Option<&str>,
) -> std::io::Result<PathBuf> {
    let directory = allocate(evidence_root, &trace_dir_name(trace_id))?;
    payload[PAYLOAD_KEY] = serde_json::json!(directory.to_string_lossy());
    Ok(directory)
}

/// The scratch directory `payload` already records (a retry keeps the one
/// its first attempt had), created again if it is gone; otherwise a new one,
/// recorded in `payload`.
pub(crate) fn ensure_in(
    payload: &mut serde_json::Value,
    evidence_root: &Path,
    trace_id: Option<&str>,
) -> std::io::Result<PathBuf> {
    if let Some(recorded) = payload.get(PAYLOAD_KEY).and_then(serde_json::Value::as_str) {
        let directory = PathBuf::from(recorded);
        std::fs::create_dir_all(directory.join(LOGS_DIR))?;
        return Ok(directory);
    }
    allocate_into(payload, evidence_root, trace_id)
}

/// Directory names whose contents are build output, dependency trees or
/// caches: regenerated by the next build, never evidence. A file is trimmed
/// when any directory on its path inside the scratch directory has one of
/// these names.
///
/// `build` is deliberately absent: Gradle and others put test reports there.
pub(crate) const REGENERABLE_DIRS: &[&str] = &[
    // Rust (`target`, and the `coverage-target` gates use for llvm-cov).
    "target",
    "coverage-target",
    // Elixir / Mix.
    "_build",
    "deps",
    // JavaScript and TypeScript.
    "node_modules",
    ".next",
    ".turbo",
    // Python.
    ".venv",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    // JVM, Swift, Dart.
    ".gradle",
    ".build",
    ".dart_tool",
];

/// Largest single file a trim keeps. Evidence files are small: the gate
/// runner caps each captured stream at 8 MiB, and proofs, logs and
/// screenshots are far below this. A file over 64 MiB in scratch is a
/// binary, a database or a dump; it is recorded with its size instead.
pub(crate) const KEPT_FILE_CAP_BYTES: u64 = 64 * 1024 * 1024;

/// Name of the record a trim writes in the scratch directory when it removed
/// anything.
pub(crate) const TRIMMED_RECORD_FILE: &str = "trimmed.json";

/// One file in a scratch directory, relative to it, with its size on disk (a
/// symlink's own size, not its target's).
#[derive(Debug, Clone)]
pub(crate) struct ScratchFile {
    pub(crate) path: String,
    pub(crate) bytes: u64,
}

/// What a trim removes, written as [`TRIMMED_RECORD_FILE`].
#[derive(Debug, Default, PartialEq, Eq, Serialize)]
pub(crate) struct TrimmedRecord {
    /// Every file removed, and their bytes together.
    pub(crate) files: u64,
    pub(crate) bytes: u64,
    /// The per-file cap in force.
    pub(crate) file_cap_bytes: u64,
    /// Regenerable directories, by their scratch-relative path, outermost
    /// match only.
    pub(crate) directories: Vec<TrimmedDirectory>,
    /// Files over the cap outside any regenerable directory.
    pub(crate) oversized: Vec<TrimmedFile>,
}

impl TrimmedRecord {
    pub(crate) fn is_empty(&self) -> bool {
        self.files == 0
    }
}

#[derive(Debug, PartialEq, Eq, Serialize)]
pub(crate) struct TrimmedDirectory {
    pub(crate) path: String,
    pub(crate) files: u64,
    pub(crate) bytes: u64,
}

#[derive(Debug, PartialEq, Eq, Serialize)]
pub(crate) struct TrimmedFile {
    pub(crate) path: String,
    pub(crate) bytes: u64,
}

/// The regenerable directory `path` is inside, as the path prefix ending at
/// its first matching directory component. The file name itself never
/// matches: a file named `target` is kept.
fn regenerable_root(path: &str) -> Option<&str> {
    let (directories, _file_name) = path.rsplit_once('/')?;
    let mut end = 0;
    for component in directories.split('/') {
        end += component.len();
        if REGENERABLE_DIRS.contains(&component) {
            return Some(&path[..end]);
        }
        end += 1; // the separator
    }
    None
}

/// What to remove from a scratch directory holding `files`. Pure: it decides
/// from paths and sizes.
pub(crate) fn plan_trim(files: &[ScratchFile], file_cap_bytes: u64) -> TrimmedRecord {
    let mut directories: BTreeMap<&str, (u64, u64)> = BTreeMap::new();
    let mut oversized = Vec::new();
    let mut record = TrimmedRecord {
        file_cap_bytes,
        ..TrimmedRecord::default()
    };
    for file in files {
        if let Some(root) = regenerable_root(&file.path) {
            let entry = directories.entry(root).or_default();
            entry.0 += 1;
            entry.1 += file.bytes;
        } else if file.bytes > file_cap_bytes {
            oversized.push(TrimmedFile {
                path: file.path.clone(),
                bytes: file.bytes,
            });
        } else {
            continue;
        }
        record.files += 1;
        record.bytes += file.bytes;
    }
    record.directories = directories
        .into_iter()
        .map(|(path, (files, bytes))| TrimmedDirectory {
            path: path.to_string(),
            files,
            bytes,
        })
        .collect();
    oversized.sort_by(|a, b| a.path.cmp(&b.path));
    record.oversized = oversized;
    record
}

/// Every file under `root`, relative to it, without following symlinks.
fn list_files(root: &Path) -> std::io::Result<Vec<ScratchFile>> {
    let mut files = Vec::new();
    let mut pending = vec![root.to_path_buf()];
    while let Some(directory) = pending.pop() {
        for entry in std::fs::read_dir(&directory)? {
            let entry = entry?;
            let metadata = std::fs::symlink_metadata(entry.path())?;
            if metadata.is_dir() {
                pending.push(entry.path());
                continue;
            }
            let relative = entry.path().strip_prefix(root).map_or_else(
                |_| entry.path().to_string_lossy().into_owned(),
                |path| path.to_string_lossy().into_owned(),
            );
            files.push(ScratchFile {
                path: relative,
                bytes: metadata.len(),
            });
        }
    }
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(files)
}

/// Remove build output and oversized files from the scratch directory and
/// record what was removed in [`TRIMMED_RECORD_FILE`]. A missing directory
/// has nothing to trim. Returns the record.
pub(crate) fn trim(scratch: &Path, file_cap_bytes: u64) -> std::io::Result<TrimmedRecord> {
    if !scratch.is_dir() {
        return Ok(TrimmedRecord::default());
    }
    let record = plan_trim(&list_files(scratch)?, file_cap_bytes);
    if record.is_empty() {
        return Ok(record);
    }
    for directory in &record.directories {
        std::fs::remove_dir_all(scratch.join(&directory.path))?;
    }
    for file in &record.oversized {
        std::fs::remove_file(scratch.join(&file.path))?;
    }
    std::fs::write(scratch.join(TRIMMED_RECORD_FILE), serde_json::to_vec_pretty(&record)?)?;
    tracing::info!(
        files = record.files,
        bytes = record.bytes,
        scratch = %scratch.display(),
        "removed build output and oversized files from the run's scratch directory"
    );
    Ok(record)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn file(path: &str, bytes: u64) -> ScratchFile {
        ScratchFile {
            path: path.to_string(),
            bytes,
        }
    }

    #[test]
    fn evidence_files_are_kept() {
        let files = [
            file("proof.json", 200),
            file("logs/red.log", 4_000),
            file("armature/shots/a.png", 90_000),
        ];
        assert!(plan_trim(&files, KEPT_FILE_CAP_BYTES).is_empty());
    }

    /// The two 2026-11 ops-01 cases: a coverage target directory and an
    /// integration checkout's dependency and build trees.
    #[test]
    fn build_output_and_dependency_trees_are_trimmed_and_recorded() {
        let files = [
            file("coverage-target/debug/deps/foundryd-1a2b", 480_000_000),
            file("coverage-target/debug/build/x/out", 10),
            file("integration/bedrock/apps/bedrock/deps/jason/_build/a.beam", 7),
            file("integration/bedrock/apps/bedrock/deps/jason/mix.exs", 3),
            file("integration/report.md", 100),
        ];
        assert_eq!(
            plan_trim(&files, KEPT_FILE_CAP_BYTES),
            TrimmedRecord {
                files: 4,
                bytes: 480_000_020,
                file_cap_bytes: KEPT_FILE_CAP_BYTES,
                directories: vec![
                    TrimmedDirectory {
                        path: "coverage-target".to_string(),
                        files: 2,
                        bytes: 480_000_010,
                    },
                    TrimmedDirectory {
                        path: "integration/bedrock/apps/bedrock/deps".to_string(),
                        files: 2,
                        bytes: 10,
                    },
                ],
                oversized: vec![],
            }
        );
    }

    #[test]
    fn a_file_over_the_cap_is_recorded_with_its_size() {
        let files = [file("dump.sqlite", 101), file("small.log", 100)];
        let record = plan_trim(&files, 100);
        assert_eq!(
            record.oversized,
            [TrimmedFile {
                path: "dump.sqlite".to_string(),
                bytes: 101,
            }]
        );
        assert_eq!((record.files, record.bytes), (1, 101));
    }

    #[test]
    fn only_directory_components_match() {
        // A file named like a regenerable directory is kept.
        assert_eq!(regenerable_root("target"), None);
        assert_eq!(regenerable_root("logs/deps"), None);
        // Similar names are not regenerable directories.
        assert_eq!(regenerable_root("targets/a"), None);
        assert_eq!(regenerable_root("build/reports/index.html"), None);
        assert_eq!(regenerable_root("node_modules/a/b.js"), Some("node_modules"));
        assert_eq!(regenerable_root("a/target/b/target/c"), Some("a/target"));
    }

    #[test]
    fn trim_removes_build_output_from_disk_and_keeps_evidence() {
        let root = tempfile::tempdir().unwrap();
        let scratch = allocate(root.path(), "trace").unwrap();
        std::fs::write(scratch.join(PROOF_FILE), "{}").unwrap();
        std::fs::write(scratch.join(LOGS_DIR).join("1.stdout.log"), "ok").unwrap();
        std::fs::create_dir_all(scratch.join("coverage-target/debug")).unwrap();
        std::fs::write(scratch.join("coverage-target/debug/bin"), "0123456789").unwrap();
        std::fs::write(scratch.join("dump.sqlite"), "0123456789").unwrap();

        let record = trim(&scratch, 5).unwrap();

        assert_eq!((record.files, record.bytes), (2, 20));
        assert!(!scratch.join("coverage-target").exists());
        assert!(!scratch.join("dump.sqlite").exists());
        assert!(scratch.join(PROOF_FILE).is_file());
        assert!(scratch.join(LOGS_DIR).join("1.stdout.log").is_file());
        let written: serde_json::Value =
            serde_json::from_slice(&std::fs::read(scratch.join(TRIMMED_RECORD_FILE)).unwrap())
                .unwrap();
        assert_eq!(written["directories"][0]["path"], "coverage-target");
        assert_eq!(written["oversized"][0]["path"], "dump.sqlite");
    }

    #[test]
    fn a_trim_with_nothing_to_remove_writes_no_record() {
        let root = tempfile::tempdir().unwrap();
        let scratch = allocate(root.path(), "trace").unwrap();
        std::fs::write(scratch.join(PROOF_FILE), "{}").unwrap();
        assert!(trim(&scratch, KEPT_FILE_CAP_BYTES).unwrap().is_empty());
        assert!(!scratch.join(TRIMMED_RECORD_FILE).exists());
        assert!(trim(&root.path().join("absent"), 1).unwrap().is_empty());
    }

    #[test]
    fn a_retry_keeps_its_scratch_and_a_new_task_run_gets_a_fresh_one() {
        let root = tempfile::tempdir().unwrap();
        let mut payload = serde_json::json!({});
        let first = ensure_in(&mut payload, root.path(), Some("trace")).unwrap();
        assert!(first.starts_with(root.path().join("trace")));
        assert!(first.join(LOGS_DIR).is_dir());
        assert_eq!(payload["scratch_dir"], first.to_string_lossy().as_ref());

        assert_eq!(ensure_in(&mut payload, root.path(), Some("trace")).unwrap(), first);

        let fresh = allocate_into(&mut payload, root.path(), Some("trace")).unwrap();
        assert_ne!(fresh, first);
        assert_eq!(payload["scratch_dir"], fresh.to_string_lossy().as_ref());
    }
}
