//! Which unlanded `.foundry` files Finalize Task copies into the evidence
//! store, and the record of the ones it leaves out.
//!
//! The archive exists so that nothing under `.foundry` disappears
//! unrecorded when a task worktree is cleaned. Most of it is small: proofs,
//! logs, screenshots, harness output. Gates that build inside `.foundry`
//! (a coverage `CARGO_TARGET_DIR`, an integration checkout with its `deps`
//! and `_build`) leave gigabytes of regenerable output there too, and
//! copying it filled the ops host's disk. So a file is copied unless it is
//! inside a regenerable directory ([`REGENERABLE_DIRS`]) or larger than
//! [`ARCHIVE_FILE_CAP_BYTES`]. What is left out is still recorded, in
//! [`SkippedRecord`]: each regenerable directory with its file count and
//! bytes, and each oversized file with its size.
//!
//! This module is pure: it decides from paths and sizes. Finalize Task
//! measures the files, copies the plan and writes the record.

use std::collections::BTreeMap;

use serde::Serialize;

/// Directory names whose contents are build output, dependency trees or
/// caches: regenerated by the next build, never evidence. A file is skipped
/// when any directory on its path below `.foundry` has one of these names.
///
/// `build` is deliberately absent: Gradle and others put test reports there.
pub(crate) const REGENERABLE_DIRS: &[&str] = &[
    // Rust (`target`, and the `coverage-target` gates use for llvm-cov).
    "target",
    "coverage-target",
    // Elixir / Mix.
    "_build",
    "deps",
    // JavaScript and TypeScript.
    "node_modules",
    ".next",
    ".turbo",
    // Python.
    ".venv",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    // JVM, Swift, Dart.
    ".gradle",
    ".build",
    ".dart_tool",
];

/// Largest single file the archive copies. Evidence files are small: the
/// gate runner caps each captured stream at 8 MiB, and proofs, logs and
/// screenshots are far below this. A file over 64 MiB under `.foundry` is a
/// binary, a database or a dump; it is recorded with its size instead.
pub(crate) const ARCHIVE_FILE_CAP_BYTES: u64 = 64 * 1024 * 1024;

/// Name of the record written beside the `worktree` mirror when anything was
/// left out of it.
pub(crate) const SKIPPED_RECORD_FILE: &str = "worktree-skipped.json";

/// One unlanded file, repository-relative, with its size on disk (a symlink's
/// own size, not its target's).
#[derive(Debug, Clone)]
pub(crate) struct UnlandedFile {
    pub(crate) path: String,
    pub(crate) bytes: u64,
}

/// What to copy, and the record of what not to.
#[derive(Debug)]
pub(crate) struct ArchivePlan {
    /// Repository-relative paths to copy, in input order.
    pub(crate) copy: Vec<String>,
    pub(crate) skipped: SkippedRecord,
}

/// The files the archive left out, written as `worktree-skipped.json`.
#[derive(Debug, Default, PartialEq, Eq, Serialize)]
pub(crate) struct SkippedRecord {
    /// Every file left out, and their bytes together.
    pub(crate) files: u64,
    pub(crate) bytes: u64,
    /// The per-file cap in force.
    pub(crate) file_cap_bytes: u64,
    /// Regenerable directories, by their repository-relative path, outermost
    /// match only.
    pub(crate) directories: Vec<SkippedDirectory>,
    /// Files over the cap outside any regenerable directory.
    pub(crate) oversized: Vec<SkippedFile>,
}

impl SkippedRecord {
    pub(crate) fn is_empty(&self) -> bool {
        self.files == 0
    }
}

#[derive(Debug, PartialEq, Eq, Serialize)]
pub(crate) struct SkippedDirectory {
    pub(crate) path: String,
    pub(crate) files: u64,
    pub(crate) bytes: u64,
}

#[derive(Debug, PartialEq, Eq, Serialize)]
pub(crate) struct SkippedFile {
    pub(crate) path: String,
    pub(crate) bytes: u64,
}

/// The regenerable directory `path` is inside, as the path prefix ending at
/// the first matching component below the top-level `.foundry`. The file
/// name itself never matches: `.foundry/target` as a file is kept.
fn regenerable_root(path: &str) -> Option<&str> {
    let (directories, _file_name) = path.rsplit_once('/')?;
    let mut end = 0;
    for (depth, component) in directories.split('/').enumerate() {
        end += component.len();
        if depth > 0 && REGENERABLE_DIRS.contains(&component) {
            return Some(&path[..end]);
        }
        end += 1; // the separator
    }
    None
}

/// Split `files` into what to copy and what to record as skipped.
pub(crate) fn plan_archive(files: &[UnlandedFile], file_cap_bytes: u64) -> ArchivePlan {
    let mut copy = Vec::new();
    let mut directories: BTreeMap<&str, (u64, u64)> = BTreeMap::new();
    let mut oversized = Vec::new();
    let mut skipped = SkippedRecord {
        file_cap_bytes,
        ..SkippedRecord::default()
    };
    for file in files {
        if let Some(root) = regenerable_root(&file.path) {
            let entry = directories.entry(root).or_default();
            entry.0 += 1;
            entry.1 += file.bytes;
        } else if file.bytes > file_cap_bytes {
            oversized.push(SkippedFile {
                path: file.path.clone(),
                bytes: file.bytes,
            });
        } else {
            copy.push(file.path.clone());
            continue;
        }
        skipped.files += 1;
        skipped.bytes += file.bytes;
    }
    skipped.directories = directories
        .into_iter()
        .map(|(path, (files, bytes))| SkippedDirectory {
            path: path.to_string(),
            files,
            bytes,
        })
        .collect();
    oversized.sort_by(|a, b| a.path.cmp(&b.path));
    skipped.oversized = oversized;
    ArchivePlan { copy, skipped }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn file(path: &str, bytes: u64) -> UnlandedFile {
        UnlandedFile {
            path: path.to_string(),
            bytes,
        }
    }

    #[test]
    fn evidence_files_are_copied() {
        let files = [
            file(".foundry/proof.json", 200),
            file(".foundry/logs/red.log", 4_000),
            file(".foundry/armature/shots/a.png", 90_000),
        ];
        let plan = plan_archive(&files, ARCHIVE_FILE_CAP_BYTES);
        assert_eq!(
            plan.copy,
            [
                ".foundry/proof.json",
                ".foundry/logs/red.log",
                ".foundry/armature/shots/a.png"
            ]
        );
        assert!(plan.skipped.is_empty());
    }

    /// The two 2026-11 ops-01 cases: a coverage target directory and an
    /// integration checkout's dependency and build trees.
    #[test]
    fn build_output_and_dependency_trees_are_recorded_not_copied() {
        let files = [
            file(".foundry/coverage-target/debug/deps/foundryd-1a2b", 480_000_000),
            file(".foundry/coverage-target/debug/build/x/out", 10),
            file(".foundry/integration/bedrock/apps/bedrock/deps/jason/_build/a.beam", 7),
            file(".foundry/integration/bedrock/apps/bedrock/deps/jason/mix.exs", 3),
            file(".foundry/integration/report.md", 100),
        ];
        let plan = plan_archive(&files, ARCHIVE_FILE_CAP_BYTES);
        assert_eq!(plan.copy, [".foundry/integration/report.md"]);
        assert_eq!(
            plan.skipped,
            SkippedRecord {
                files: 4,
                bytes: 480_000_020,
                file_cap_bytes: ARCHIVE_FILE_CAP_BYTES,
                directories: vec![
                    SkippedDirectory {
                        path: ".foundry/coverage-target".to_string(),
                        files: 2,
                        bytes: 480_000_010,
                    },
                    SkippedDirectory {
                        path: ".foundry/integration/bedrock/apps/bedrock/deps".to_string(),
                        files: 2,
                        bytes: 10,
                    },
                ],
                oversized: vec![],
            }
        );
    }

    #[test]
    fn a_file_over_the_cap_is_recorded_with_its_size() {
        let files = [
            file(".foundry/dump.sqlite", 101),
            file(".foundry/small.log", 100),
        ];
        let plan = plan_archive(&files, 100);
        assert_eq!(plan.copy, [".foundry/small.log"]);
        assert_eq!(
            plan.skipped.oversized,
            [SkippedFile {
                path: ".foundry/dump.sqlite".to_string(),
                bytes: 101,
            }]
        );
        assert_eq!((plan.skipped.files, plan.skipped.bytes), (1, 101));
    }

    #[test]
    fn only_directory_components_below_dot_foundry_match() {
        // A file named like a regenerable directory is kept.
        assert_eq!(regenerable_root(".foundry/target"), None);
        assert_eq!(regenerable_root(".foundry/logs/deps"), None);
        // Similar names are not regenerable directories.
        assert_eq!(regenerable_root(".foundry/targets/a"), None);
        assert_eq!(regenerable_root(".foundry/build/reports/index.html"), None);
        assert_eq!(regenerable_root(".foundry/node_modules/a/b.js"), Some(".foundry/node_modules"));
        assert_eq!(regenerable_root(".foundry/a/target/b/target/c"), Some(".foundry/a/target"));
    }
}
